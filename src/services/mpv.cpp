/* writeSessionCookies
- Turns the cookie header saved by `moroder setup` (browser.json) into a
  Netscape cookies.txt that yt-dlp can read with --cookies
- This needs no browser at all: it works whatever browser the headers came from
  (Arc, Safari...) and doesn't touch a browser's cookie store, which macOS
  guards (app data permissions, Keychain)
- Returns the file path, or empty if there is no session to export
*/
std::filesystem::path writeSessionCookies(const Config& cfg) {
    namespace fs = std::filesystem;

    const fs::path auth = cfg.YTM_COOKIES_PATH / "browser.json";

    std::ifstream in(auth);
    if (!in.is_open()) return {};

    nlohmann::json raw = nlohmann::json::parse(in, nullptr, false);
    if (!raw.is_object()) return {};

    std::string cookie;
    for (auto& [k, v] : raw.items()) {
        if (utils::lower(k) == "cookie" && v.is_string()) cookie = v.get<std::string>();
    }
    if (cookie.empty()) return {};

    const fs::path out_path = cfg.YTM_COOKIES_PATH / "cookies.txt";
    const long expiry = static_cast<long>(std::time(nullptr)) + 365L * 24 * 3600;

    std::ostringstream out;
    out << "# Netscape HTTP Cookie File\n# Generated by moroder from browser.json\n";

    std::istringstream pairs(cookie);
    std::string pair;
    while (std::getline(pairs, pair, ';')) {
        pair = utils::trim(pair);
        const size_t eq = pair.find('=');
        if (eq == std::string::npos || eq == 0) continue;

        out << ".youtube.com\tTRUE\t/\tTRUE\t" << expiry << "\t"
            << pair.substr(0, eq) << "\t" << pair.substr(eq + 1) << "\n";
    }

    {
        std::ofstream file(out_path, std::ios::trunc);
        if (!file.is_open()) return {};
        file << out.str();
    }

    // Same sensitivity as browser.json.
    std::error_code perm_ec;
    fs::permissions(out_path, fs::perms::owner_read | fs::perms::owner_write, fs::perm_options::replace, perm_ec);
    return out_path;
}

